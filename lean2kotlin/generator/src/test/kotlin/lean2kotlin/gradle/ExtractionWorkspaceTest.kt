package lean2kotlin.gradle

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

// 合成テキストは抽出器の入力で IR のバイトに効く — 文字列をバイトどおりに固定する
class ExtractionWorkspaceTest {

	@Test
	fun `domainPackageName は行頭の最初の name を読む`() {
		assertEquals("sprout-lean", ExtractionWorkspace.domainPackageName(
			"name = \"sprout-lean\"\nversion = \"0.1.0\"\n\n[[require]]\nname = \"dep\"\n"))
		assertEquals("x", ExtractionWorkspace.domainPackageName("name=\"x\"\n"))
		assertEquals("x", ExtractionWorkspace.domainPackageName("# 対象ドメイン\nname   =   \"x\"\n"))
		assertEquals("y", ExtractionWorkspace.domainPackageName("  name = \"x\"\nname = \"y\"\n"))
	}

	@Test
	fun `domainPackageName は行頭の name が無ければ null`() {
		assertNull(ExtractionWorkspace.domainPackageName("version = \"0.1.0\"\n"))
		assertNull(ExtractionWorkspace.domainPackageName("  name = \"x\"\n"))
		assertNull(ExtractionWorkspace.domainPackageName("name = \"\"\n"))
		assertNull(ExtractionWorkspace.domainPackageName(""))
	}

	@Test
	fun `lakefile は対象と抽出器を絶対パスで require する`() {
		assertEquals(
			"""
			|# GENERATED by lean2kotlin plugin — 抽出ワークスペース(設定から合成)
			|name = "lean2kotlin-extraction"
			|
			|[[require]]
			|name = "sprout-lean"
			|path = "/w/scaffold-check/build/scaffold/lean"
			|
			|[[require]]
			|name = "lean2kotlin"
			|path = "/w/lean"
			|""".trimMargin(),
			ExtractionWorkspace.lakefile("sprout-lean", "/w/scaffold-check/build/scaffold/lean", "/w/lean"))
	}

	@Test
	fun `driver は binder 上書きをキー順に 1 行ずつ並べる`() {
		assertEquals(
			"""
			|-- GENERATED by lean2kotlin plugin — 設定(build.gradle.kts)から合成される
			|import Lobby
			|import Lean2Kotlin.Extract
			|
			|-- 契約定理の演繹は Lean 内評価(オラクル)を多用する — 既定の上限では足りない
			|set_option maxHeartbeats 4000000 in
			|#kotlin_ir "Lobby" "/w/port/build/lean2kotlin/lean2kotlin-ir.json"
			|  "G=Lobby.Application.VisitIdGeneratorState"
			|  "P=Lobby.Application.PaymentAttemptIdGeneratorState"
			|""".trimMargin(),
			ExtractionWorkspace.driver("Lobby", "/w/port/build/lean2kotlin/lean2kotlin-ir.json", linkedMapOf(
				"P" to "Lobby.Application.PaymentAttemptIdGeneratorState",
				"G" to "Lobby.Application.VisitIdGeneratorState")))
	}

	@Test
	fun `driver は binder 上書きが無ければ出力パスで行を終える`() {
		assertEquals(
			"""
			|-- GENERATED by lean2kotlin plugin — 設定(build.gradle.kts)から合成される
			|import Sprout
			|import Lean2Kotlin.Extract
			|
			|-- 契約定理の演繹は Lean 内評価(オラクル)を多用する — 既定の上限では足りない
			|set_option maxHeartbeats 4000000 in
			|#kotlin_ir "Sprout" "/w/ir.json"
			|""".trimMargin(),
			ExtractionWorkspace.driver("Sprout", "/w/ir.json", emptyMap()))
	}
}
