import test from "node:test";
import assert from "node:assert/strict";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { tempProject, cleanEnv, runNode, writeTree, commitAll } from "./helpers.mjs";

const regenImpact = fileURLToPath(new URL("../.apm/skills/cradle/scripts/regen-impact.mjs", import.meta.url));

const GEN = "// GENERATED by lean2kotlin — DO NOT EDIT\n\npackage p\n\n";
const main = "backend/src/generated/kotlin-main";
const testGen = "backend/src/generated/kotlin-test";
const adapterGen = "backend/src/generated/kotlin-adapter-test";
// コミット時点の生成物
const before = {
  [`${main}/domain/repository/NoteRepository.kt`]: `${GEN}interface NoteRepository {\n\tfun find(id: NoteId): Note?\n\n\tfun save(note: Note)\n}\n`,
  [`${main}/domain/entity/Note.kt`]: `${GEN}data class Note(val id: NoteId, val title: String)\n`,
  [`${main}/domain/entity/Legacy.kt`]: `${GEN}data class Legacy(val x: Int)\n`,
  [`${testGen}/domain/repository/NoteRepositoryContractTest.kt`]: `${GEN}abstract class NoteRepositoryContractTest {\n\tprotected abstract fun repository(): NoteRepository\n}\n`,
};
// 再生成の後: find の署名が変わり save が消えて delete が増える・Note の型の行が変わる・Legacy が消える・
// Port の interface と Adapter 適合テストが新しく現れる・契約テストに抽象メソッドが増える
const after = {
  [`${main}/domain/repository/NoteRepository.kt`]: `${GEN}interface NoteRepository {\n\tfun find(id: NoteId): Note\n\n\tfun delete(id: NoteId)\n}\n`,
  [`${main}/domain/entity/Note.kt`]: `${GEN}data class Note(val id: NoteId, val title: String, val closed: Boolean)\n`,
  [`${main}/application/port/directory/Directory.kt`]: `${GEN}interface Directory {\n\tfun find(request: DirectoryFindRequest): DirectoryFindOutcome\n}\n`,
  [`${testGen}/domain/repository/NoteRepositoryContractTest.kt`]: `${GEN}abstract class NoteRepositoryContractTest {\n\tprotected abstract fun repository(): NoteRepository\n\n\tprotected abstract fun clock(): Clock\n}\n`,
  [`${adapterGen}/application/port/directory/DirectoryAdapterContractTest.kt`]: `${GEN}abstract class DirectoryAdapterContractTest {\n\tprotected abstract fun adapter(): Directory\n}\n`,
};
// 手書き: Repository の実装・Note を使う Controller・契約テストの配線（src/test）・Adapter 適合テストの配線（src/adapterTest）
const hand = {
  "backend/src/main/kotlin/p/infrastructure/ExposedNoteRepository.kt": "package p\n\nclass ExposedNoteRepository : NoteRepository {\n\toverride fun find(id: NoteId): Note? = null\n\n\toverride fun save(note: Note) = Unit\n}\n",
  "backend/src/main/kotlin/p/presentation/NoteController.kt": "package p\n\nclass NoteController(private val repository: NoteRepository) {\n\tfun show(id: NoteId): Note? = repository.find(id)\n}\n",
  "backend/src/test/kotlin/p/NoteRepositoryContractTestImpl.kt": "package p\n\nclass NoteRepositoryContractTestImpl : NoteRepositoryContractTest() {\n\toverride fun repository(): NoteRepository = ExposedNoteRepository()\n}\n",
  "backend/src/adapterTest/kotlin/p/DirectoryAdapterContractTestImpl.kt": "package p\n\nclass DirectoryAdapterContractTestImpl : DirectoryAdapterContractTest() {\n\toverride fun adapter(): Directory = HttpDirectory()\n}\n",
};

// 一時プロジェクト（git 管理）: 生成物と手書きをコミットし、backend.regenerate は regen/ に置いた再生成後の写しを生成ディレクトリへ重ねて Legacy.kt を消す。
// gradle も Lean も要らない（regenerate は backend/ を cwd に sh で走る）
function fixture(t, regenerate = "cp -R ../regen/. src/generated/ && rm src/generated/kotlin-main/domain/entity/Legacy.kt") {
  const root = tempProject(t, "cradle-regen-impact-", { project: "Example", backend: { regenerate } });
  writeTree(root, { ...before, ...hand });
  writeTree(join(root, "regen"), Object.fromEntries(Object.entries(after).map(([rel, text]) => [rel.replace("backend/src/generated/", ""), text])));
  commitAll(root);
  // git status の未追跡の出し方（ディレクトリにまとめる）や diff の出力を利用者の git 設定に左右させない
  const env = cleanEnv({ GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: "/dev/null" });
  return { root, run: (...args) => runNode(regenImpact, args, { cwd: root, env }) };
}

const files = {
  legacy: `${main}/domain/entity/Legacy.kt`, note: `${main}/domain/entity/Note.kt`, repo: `${main}/domain/repository/NoteRepository.kt`,
  contract: `${testGen}/domain/repository/NoteRepositoryContractTest.kt`, adapterTest: `${adapterGen}/application/port/directory/DirectoryAdapterContractTest.kt`, port: `${main}/application/port/directory/Directory.kt`,
};
const exposed = "backend/src/main/kotlin/p/infrastructure/ExposedNoteRepository.kt";
const controller = "backend/src/main/kotlin/p/presentation/NoteController.kt";
const sym = (symbol, kind, file, referencedBy = []) => ({ symbol, kinds: [kind], generatedFiles: [file], referencedBy });
// 追跡済みの差分（diff --name-status の順）の後に未追跡（ls-files --others の順）。シンボルは参照元の多い順、同数なら名前順。
// src/adapterTest で配線した DirectoryAdapterContractTest も未配線に出る（regen-impact は src/main と src/test しか見ない）
const expected = {
  changedGeneratedFiles: [
    { status: "D", path: files.legacy }, { status: "M", path: files.note }, { status: "M", path: files.repo }, { status: "M", path: files.contract },
    { status: "A", path: files.adapterTest }, { status: "A", path: files.port },
  ],
  symbols: [
    sym("Note", "changed", files.note, [exposed, controller]),
    sym("NoteRepository.find", "changed", files.repo, [exposed, controller]),
    sym("NoteRepository.save", "removed", files.repo, [exposed]),
    sym("Directory", "added", files.port),
    sym("Directory.find", "added", files.port),
    sym("DirectoryAdapterContractTest", "added", files.adapterTest),
    sym("DirectoryAdapterContractTest.adapter", "added", files.adapterTest),
    sym("Legacy", "removed", files.legacy),
    sym("NoteRepository.delete", "added", files.repo),
    sym("NoteRepositoryContractTest.clock", "added", files.contract),
  ],
  unwiredContractTests: ["DirectoryAdapterContractTest"],
  golden: null,
  restored: false,
};
const expectedText = [
  "# regen-impact — Example",
  "",
  "生成物の差分: 6 ファイル",
  `  D ${files.legacy}`, `  M ${files.note}`, `  M ${files.repo}`, `  M ${files.contract}`, `  A ${files.adapterTest}`, `  A ${files.port}`,
  "",
  "影響を受ける手書きコード（変わった生成シンボルを参照している）: 3 シンボル",
  "  Note [changed]", `      ${exposed}`, `      ${controller}`,
  "  NoteRepository.find [changed]", `      ${exposed}`, `      ${controller}`,
  "  NoteRepository.save [removed]", `      ${exposed}`,
  "",
  "参照元の無い生成シンボル（新規 interface など — これから実装するもの）: Directory, Directory.find, DirectoryAdapterContractTest, DirectoryAdapterContractTest.adapter, Legacy, NoteRepository.delete, NoteRepositoryContractTest.clock",
  "",
  "未配線の契約テスト: DirectoryAdapterContractTest",
].join("\n") + "\n";

test("再生成してから生成物の差分・変わったシンボルと参照元・未配線の契約テストを --json で出し、--no-regen は作業ツリーの同じ差分を読む", (t) => {
  const { run } = fixture(t);
  const regen = run("--no-golden", "--json");
  assert.equal(regen.status, 0, regen.stderr);
  assert.equal(regen.stderr, "");
  assert.equal(regen.stdout, JSON.stringify(expected, null, 2) + "\n");
  const read = run("--no-regen", "--no-golden", "--json");
  assert.equal(read.status, 0, read.stderr);
  assert.equal(read.stdout, regen.stdout);
});

test("文字の出力は差分・参照元のあるシンボル・参照元の無いシンボル・未配線の契約テストの順。golden-check が動かなければその stderr を添える", (t) => {
  const { root, run } = fixture(t);
  assert.equal(run("--no-golden").status, 0);
  const text = run("--no-regen", "--no-golden");
  assert.equal(text.status, 0, text.stderr);
  assert.equal(text.stdout, expectedText);
  // golden/ が無い golden-check は fail で止まり、stdout が空なので stderr の末尾を「実行できず」に載せる（stderr の改行も残る）
  const golden = run("--no-regen");
  assert.equal(golden.status, 0, golden.stderr);
  assert.equal(golden.stdout, `${expectedText}\ngolden 回帰: 実行できず — cradle: golden ディレクトリがありません: ${join(root, "lean/golden")}\n\n`);
});

test("生成ディレクトリに未コミットの差分があれば再生成せずに止まり、再生成が失敗すればその出力の末尾を出して 2 で終わる", (t) => {
  const { run } = fixture(t);
  assert.equal(run("--no-golden").status, 0);
  const dirty = run("--no-golden", "--json");
  assert.equal(dirty.status, 1);
  assert.equal(dirty.stdout, "");
  assert.equal(dirty.stderr, [
    "cradle: 生成ディレクトリに未コミットの差分があります。先にコミットするか、差分だけ読むなら --no-regen:",
    ` D ${files.legacy}`, ` M ${files.note}`, ` M ${files.repo}`, ` M ${files.contract}`,
    "?? backend/src/generated/kotlin-adapter-test/", "?? backend/src/generated/kotlin-main/application/",
  ].join("\n") + "\n");
  const { run: broken } = fixture(t, "echo boom; exit 3");
  const failed = broken("--no-golden", "--json");
  assert.equal(failed.status, 2);
  assert.equal(failed.stdout, "");
  assert.equal(failed.stderr, "cradle: 再生成に失敗しました（echo boom; exit 3）:\nboom\n\n");
});
