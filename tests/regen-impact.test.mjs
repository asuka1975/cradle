// 別の git が index.lock を持つと後始末の git checkout が断る（ls-files と diff はロックを取らずに読むので通る）。
// git の文は言語の設定で変わるので、git の stderr はロックのファイル名でだけ確かめる
const unrestored = "--dry-run の後始末で生成ディレクトリを HEAD に戻せませんでした（今回の出力が残っています）: Command failed: git checkout -- backend/src/generated\n";
test("--dry-run の後始末の git が失敗すれば、スタックトレースでなく戻せなかったことと git の理由を cradle: の文で言い、2 で終わる", (t) => {
  // 再生成が通ったあと: 結果を出さずに止まり、今回の出力は生成ディレクトリに残る
  const { run, porcelain } = fixture(t, "cp -R ../regen/. src/generated/ && rm src/generated/kotlin-main/domain/entity/Legacy.kt && touch ../.git/index.lock");
  const ok = run("--no-golden", "--dry-run", "--json");
  assert.equal(ok.status, 2);
  assert.equal(ok.stdout, "");
  assert.ok(ok.stderr.startsWith(`cradle: ${unrestored}`), ok.stderr);
  assert.match(ok.stderr, /index\.lock/);
  assert.doesNotMatch(ok.stderr, /^\s+at /m);
  assert.equal(porcelain(), dirtyLines.join("\n") + "\n");
  // 再生成が失敗したとき: 再生成の失敗の文と出力の末尾はそのままで、戻せなかったことを後ろに添える
  const regenerate = "cp -R ../regen/. src/generated/ && touch ../.git/index.lock && echo boom && exit 3";
  const { run: broken } = fixture(t, regenerate);
  const failed = broken("--no-golden", "--dry-run");
  assert.equal(failed.status, 2);
  assert.equal(failed.stdout, "");
  assert.ok(failed.stderr.startsWith(`cradle: 再生成に失敗しました（${regenerate}）:\nboom\n\n${unrestored}`), failed.stderr);
  assert.match(failed.stderr, /index\.lock/);
  assert.doesNotMatch(failed.stderr, /^\s+at /m);
});

// 生成ディレクトリがまだ無いプロジェクト（初めての再生成の前）: 手書きだけをコミットし、書きかけの手書きとメモは未追跡で置く
function fresh(t, regenerate) {
  const root = tempProject(t, "cradle-regen-fresh-", { project: "Example", backend: { regenerate } });
  writeTree(root, { "backend/src/main/kotlin/p/Main.kt": "package p\n\nfun main() = Unit\n" });
  commitAll(root);
  writeTree(root, { "backend/src/main/kotlin/p/Draft.kt": "package p\n\nclass Draft\n", "notes.md": "メモ\n" });
  return runner(root);
}
const untrackedHand = "?? backend/src/main/kotlin/p/Draft.kt\n?? notes.md\n";
const writeA = "mkdir -p src/generated/kotlin-main && printf 'package p\\n\\nclass A\\n' > src/generated/kotlin-main/A.kt";

test("生成ディレクトリがまだ無ければ、--dry-run の後始末は今回の出力だけを消し、生成ディレクトリの外の未追跡を消さない", (t) => {
  const { run, porcelain } = fresh(t, writeA);
  // 戻すものが何も無い: 生成ディレクトリの無い git clean はリポジトリ全体の未追跡を消してしまう
  const read = run("--no-regen", "--no-golden", "--dry-run", "--json");
  assert.equal(read.status, 0, read.stderr);
  assert.equal(JSON.parse(read.stdout).restored, true);
  assert.equal(porcelain(), untrackedHand);
  // 再生成が作った（HEAD に無い）生成ディレクトリは checkout せず clean だけで消す
  const regen = run("--no-golden", "--dry-run", "--json");
  assert.equal(regen.status, 0, regen.stderr);
  assert.deepEqual(JSON.parse(regen.stdout).changedGeneratedFiles, [{ status: "A", path: "backend/src/generated/kotlin-main/A.kt" }]);
  assert.equal(porcelain(), untrackedHand);
  const { run: broken, porcelain: brokenPorcelain } = fresh(t, `${writeA} && echo boom && exit 3`);
  const failed = broken("--no-golden", "--dry-run");
  assert.equal(failed.status, 2);
  assert.equal(failed.stderr, `cradle: 再生成に失敗しました（${writeA} && echo boom && exit 3）:\nboom\n\n`);
  assert.equal(brokenPorcelain(), untrackedHand);
});

// 偽の Lean CLI（lean/.lake/build/bin/<project 小文字>）: リクエストの cmd で canned.json の応答を返す
const fakeCli = `#!${process.execPath}
const fs = require("fs"); const path = require("path");
const req = JSON.parse(fs.readFileSync(0, "utf8"));
process.stdout.write(JSON.stringify(JSON.parse(fs.readFileSync(path.join(__dirname, "canned.json"), "utf8"))[req.cmd]));
`;

test("golden 回帰は golden-check の changed/error の数を言い、ok 以外の行を golden-check と同じ言い方（先頭の行）で並べる", (t) => {
  const { root, run } = fixture(t);
  const init = { ok: { state: { n: 0 } } };
  const trace = (n) => ({ ok: { trace: [{ observation: { tick: {} }, state: { n } }] } });
  writeTree(root, {
    // half は init が無い（error）うえに再生のリクエストも無い（skipped）。moved は内部入力の手で食い違う（changed）
    "lean/golden/half-flow.json": JSON.stringify({ ok: {} }),
    "lean/golden/moved-init.json": JSON.stringify(init),
    "lean/golden/moved-flow.json": JSON.stringify(trace(1)),
    "lean/golden/moved.request.json": JSON.stringify({ init: { cmd: "init" }, flow: { cmd: "flow", commands: [] } }),
    "lean/.lake/build/bin/example": fakeCli,
    "lean/.lake/build/bin/canned.json": JSON.stringify({ init, flow: trace(2) }),
  });
  chmodSync(join(root, "lean/.lake/build/bin/example"), 0o755);
  const text = run();
  assert.equal(text.status, 0, text.stderr);
  assert.equal(text.stdout, [
    expectedText,
    "golden 回帰: 2 件が changed/error（意図した変更か確かめる）",
    "  error    half-init: half-init.json が無い（golden は init / flow の 2 本 1 組）",
    "  skipped  half: half.request.json が無い（再生できない golden）— モックアップで採り直すか --manifest で補う",
    "  CHANGED  moved-flow: first divergence at /ok/trace/0/state/n (step #1 observation tick)",
  ].join("\n") + "\n");
  // --json の golden は golden-check --json をそのまま載せる
  const json = run("--no-regen", "--json");
  assert.equal(json.status, 0, json.stderr);
  const golden = JSON.parse(json.stdout).golden;
  assert.equal(golden.failed, 2);
  assert.deepEqual(golden.report.map(r => [r.name, r.kind, r.status]), [["half", "init", "error"], ["half", undefined, "skipped"], ["moved", "init", "ok"], ["moved", "flow", "changed"]]);
});

// core.quotePath の既定（true）の git は非 ASCII のパスを引用符と 8 進（"…/\346\211\213….kt"）で返す。Lean の名前から作る生成物のファイル名は日本語にもなる
test("生成物の差分は非 ASCII の名前のファイルも同じパスで出し、HEAD と作業ツリーの中身から変わったシンボルを読む（改名は新しいパスで出す）", (t) => {
  const proc = `${main}/domain/entity/手続き.kt`, fresh = `${main}/domain/entity/新規.kt`, old = `${main}/domain/entity/Old.kt`, renamed = `${main}/domain/entity/改名.kt`;
  const root = tempProject(t, "cradle-regen-impact-ja-", { project: "Example", backend: { regenerate: "true" } });
  writeTree(root, { [proc]: `${GEN}data class Procedure(val id: Int)\n`, [old]: `${GEN}data class Kept(val id: Int)\n` });
  commitAll(root);
  writeTree(root, { [proc]: `${GEN}data class Procedure(val id: Int, val done: Boolean)\n`, [fresh]: `${GEN}data class Fresh(val id: Int)\n` });
  git(root, "mv", old, renamed);
  const r = runNode(regenImpact, ["--no-regen", "--no-golden", "--json"], { cwd: root, env });
  assert.equal(r.status, 0, r.stderr);
  const out = JSON.parse(r.stdout);
  assert.deepEqual(out.changedGeneratedFiles, [{ status: "M", path: proc }, { status: "R", path: renamed }, { status: "A", path: fresh }]);
  assert.deepEqual(out.symbols, [sym("Fresh", "added", fresh), sym("Kept", "added", renamed), sym("Procedure", "changed", proc)]);
});

