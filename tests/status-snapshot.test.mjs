test("status は全フェーズに手が付いたプロジェクトで、フェーズごとの見出し・事実・次の一手（— なら出さない）と申し送りの数を出す", (t) => {
  const root = tempProject(t, "cradle-status-full-", config);
  writeTree(root, files);
  const r = runNode(status, [], { cwd: root, env: cleanEnv() });
  assert.equal(r.status, 0, r.stderr);
  assert.equal(r.stderr, "");
  const body = phases.flatMap(p => [`## ${p.name} — ${p.state}`, ...p.facts.map(f => `- ${f}`), ...(p.next !== "—" ? [`→ 次: ${p.next}`] : []), ""]);
  assert.equal(r.stdout, ["# Example — Cradle status", "", ...body, "申し送り（documents/ai-notes）: 2 件 — 規約ではない。ユーザー判断が要るものが無いか確かめる。"].join("\n") + "\n");
});

test("status --json は project・phases（name・state・facts・next の順）・aiNotes の順に同じ事実を出す", (t) => {
  const root = tempProject(t, "cradle-status-full-", config);
  writeTree(root, files);
  const r = runNode(status, ["--json"], { cwd: root, env: cleanEnv() });
  assert.equal(r.status, 0, r.stderr);
  assert.equal(r.stdout, JSON.stringify({ project: "Example", phases, aiNotes: 2 }, null, 2) + "\n");
});
