test("cradle は引数が無ければ使い方を 0 で、知らないコマンドには同じ使い方を 1 で出す。一覧は doctor・refs・contract-skeleton も含む入口すべて", (t) => {
  const root = tempProject(t, "cradle-usage-");
  const usage = "usage: cradle <command> [args]\n" + ["spec-query", "golden-check", "lean-check", "regen-impact", "unslop", "status", "ddd-clean-check", "hook", "doctor", "refs", "contract-skeleton", "mockup-build"].map(c => `  ${c}\n`).join("");
  const none = runNode(cradle, [], { cwd: root, env: cleanEnv() });
  assert.deepEqual([none.status, none.stdout, none.stderr], [0, usage, ""]);
  const unknown = runNode(cradle, ["nope"], { cwd: root, env: cleanEnv() });
  assert.deepEqual([unknown.status, unknown.stdout, unknown.stderr], [1, usage, ""]);
  // Object.prototype の鍵もコマンドではない（入口の表に引き当てて子プロセスを起こさない）
  for (const cmd of ["constructor", "toString", "__proto__", "hasOwnProperty"]) {
    const r = runNode(cradle, [cmd], { cwd: root, env: cleanEnv() });
    assert.deepEqual([r.status, r.stdout, r.stderr], [1, usage, ""], cmd);
  }
});

// 生成された抽象契約テストの形: package・abstract class・protected / 無印の abstract fun（戻り値の型は = か { か行末まで）・具象のテスト
const contractTest = `// GENERATED by lean2kotlin — DO NOT EDIT

package com.example.notes.domain.repository

/** Lean: \`Example.Domain.Repository.NoteRepository\` の契約。 */
abstract class NoteRepositoryContractTest {
	protected abstract fun repository(): NoteRepository

	protected abstract fun seed(notes: List<Note>, clock: Clock): Unit

	abstract fun fixtures(): Map<String, Note>

	@Test
	fun savedNoteIsFound() {
		repository().save(fixtures().getValue("a"))
	}
}
`;

const wire = (sig, type) => `\toverride fun ${sig}: ${type} = TODO("wire: 本番の実装を返す（${type}）")`;
const skeleton = (pkg) => [
  `package ${pkg}`,
  "",
  "import com.example.notes.domain.repository.NoteRepositoryContractTest",
  "",
  "/** 生成された契約テストに本番実装を配線する。Repository に fake を挟まない — 本番の実装を実 DB 相手にそのまま使う。Port は渡された生成モックを配線する。 */",
  "class NoteRepositoryContractTestImpl : NoteRepositoryContractTest() {",
  wire("repository()", "NoteRepository"),
  wire("seed(notes: List<Note>, clock: Clock)", "Unit"),
  wire("fixtures()", "Map<String, Note>"),
  "}",
  "",
].join("\n") + "\n";

test("contract-skeleton は抽象メソッドごとに TODO の override を並べた具象クラスを出し、--package は package 行だけを差し替える。値の無い --package は生成ファイルの package のまま", (t) => {
  const root = tempProject(t, "cradle-skeleton-");
  writeTree(root, { "NoteRepositoryContractTest.kt": contractTest });
  const run = (...args) => runNode(cradle, ["contract-skeleton", ...args], { cwd: root, env: cleanEnv() });
  const plain = run("NoteRepositoryContractTest.kt");
  assert.equal(plain.status, 0, plain.stderr);
  assert.equal(plain.stdout, skeleton("com.example.notes.domain.repository"));
  assert.equal(run("NoteRepositoryContractTest.kt", "--package", "com.example.notes.wiring").stdout, skeleton("com.example.notes.wiring"));
  assert.equal(run("NoteRepositoryContractTest.kt", "--package=com.example.notes.wiring").stdout, skeleton("com.example.notes.wiring"));
  assert.equal(run("--package", "com.example.notes.wiring", "NoteRepositoryContractTest.kt").stdout, skeleton("com.example.notes.wiring"));
  // 空の値（--package= や空の変数を渡した --package "$P"）も値の無い形と同じ
  for (const valueless of [["--package"], ["--package", "--force"], ["--package="], ["--package", ""], ["--package= "]]) {
    const r = run("NoteRepositoryContractTest.kt", ...valueless);
    assert.deepEqual([r.status, r.stdout, r.stderr], [0, skeleton("com.example.notes.domain.repository"), ""], JSON.stringify(valueless));
  }
});

test("contract-skeleton は引数が無ければ使い方、無いファイル・読めないパス（ディレクトリ）と abstract class の無いファイルはその旨を stderr に 1 行出して 1 で終わる", (t) => {
  const root = tempProject(t, "cradle-skeleton-");
  const run = (...args) => runNode(cradle, ["contract-skeleton", ...args], { cwd: root, env: cleanEnv() });
  const usage = run();
  assert.deepEqual([usage.status, usage.stdout, usage.stderr], [1, "", "usage: cradle contract-skeleton backend/src/generated/kotlin-test/.../XxxContractTest.kt\n"]);
  const notAbstract = run("cradle.json");
  assert.deepEqual([notAbstract.status, notAbstract.stdout, notAbstract.stderr], [1, "", "abstract class が見つかりません\n"]);
  const missing = run("Missing.kt");
  assert.deepEqual([missing.status, missing.stdout, missing.stderr], [1, "", "cradle contract-skeleton: Missing.kt が無い\n"]);
  // ディレクトリは在っても読めない。スタックトレースでなく、パスと理由の 1 行
  writeTree(root, { "generated/.keep": "" });
  const dir = run("generated");
  assert.deepEqual([dir.status, dir.stdout], [1, ""]);
  assert.match(dir.stderr, /^cradle contract-skeleton: generated を読めません: EISDIR\b[^\n]*\n$/);
  // ファイルより前の --package も値を取る。ファイルが無ければ使い方
  const flagOnly = run("--package", "com.example.notes.wiring");
  assert.deepEqual([flagOnly.status, flagOnly.stdout, flagOnly.stderr], [1, "", usage.stderr]);
});

// 一時プロジェクト（git 管理）: イベント#1 と、その ID を前方に含む イベント#10・#101・#1.1・#1a を documents・lean・README に置く
function refsFixture(t) {
  const root = tempProject(t, "cradle-refs-");
  writeTree(root, {
    "documents/ddd/event-timeline.md": "# イベント時系列マップ\n\n| # | ドメインイベント |\n|---|---|\n| 1 | 本が登録された |\n| 10 | 本が除籍された |\n",
    "documents/ddd/hotspots.md": "| HS-001 | イベント#1 の後に貸出できるか | open |\n| HS-002 | イベント#10 で予約はどうなるか | open |\n",
    "documents/ddd/model-review.md": "| MQ-001 | イベント#1.1 で分かれるか | open |\n| MQ-002 | イベント#1a は イベント#101 より前か | open |\n| MQ-003 | イベント#10 と イベント#1 は同じ本か | open |\n",
    "lean/Example/Domain/Book.lean": "/-- 本。出典: イベント#1 -/\nstructure Book where\n  id : Nat\n",
    "lean/Example/Domain/Retire.lean": "/-- 除籍。出典: イベント#10 -/\ndef retire := 1\n",
    "README.md": "# Example\n\n形式化の出典はイベント#1.\n",
  });
  commitAll(root);
  // git grep の出力（色・パスの書き方）を利用者の git 設定に左右させない
  const env = cleanEnv({ GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: "/dev/null" });
  return { root, run: (cwd, ...args) => runNode(cradle, ["refs", ...args], { cwd, env }) };
}
const refsTail = "documents 側で撤回・訂正したら、ここに出た派生（Lean の出典・openapi・infra-design・README）を洗い直すこと。\n";

test("refs はプロジェクトルートから git grep の行（path:line:content）をそのまま字下げして出す。ID は文字どおりに探し、後ろに数字・英小文字・「.数字」が続く イベント#10・#1.1・#1a は拾わない", (t) => {
  const { root, run } = refsFixture(t);
  const r = run(root, "イベント#1");
  assert.equal(r.status, 0, r.stderr);
  assert.equal(r.stderr, "");
  assert.equal(r.stdout, [
    "イベント#1: 4 箇所",
    // 文末の「.」は ID の続きではない
    "  README.md:3:形式化の出典はイベント#1.",
    "  documents/ddd/hotspots.md:1:| HS-001 | イベント#1 の後に貸出できるか | open |",
    // イベント#10 と同じ行でも、ほかに イベント#1 そのものがあれば拾う
    "  documents/ddd/model-review.md:3:| MQ-003 | イベント#10 と イベント#1 は同じ本か | open |",
    "  lean/Example/Domain/Book.lean:1:/-- 本。出典: イベント#1 -/",
  ].join("\n") + "\n" + refsTail);
  // 「.」は任意の 1 文字ではない（イベント#101 を拾わない）
  assert.equal(run(root, "イベント#1.1").stdout, "イベント#1.1: 1 箇所\n  documents/ddd/model-review.md:1:| MQ-001 | イベント#1.1 で分かれるか | open |\n" + refsTail);
  // git grep の 1（一致なし）は失敗ではない
  const none = run(root, "MQ-404");
  assert.deepEqual([none.status, none.stdout, none.stderr], [0, "MQ-404: 0 箇所\n" + refsTail, ""]);
  const usage = run(root);
  assert.deepEqual([usage.status, usage.stdout, usage.stderr], [1, "", "usage: cradle refs <HS-001|MQ-003|UX-002|INFRA-D-004|イベント#5>\n"]);
});

test("refs はサブディレクトリから呼んでもプロジェクトルートから探し、パスをルートからの相対で出す", (t) => {
  const { root, run } = refsFixture(t);
  const atRoot = run(root, "イベント#1").stdout;
  for (const cwd of [join(root, "lean"), join(root, "documents", "ddd")]) {
    const sub = run(cwd, "イベント#1");
    assert.deepEqual([sub.status, sub.stdout, sub.stderr], [0, atRoot, ""], cwd);
  }
});

test("refs は利用者の git 設定（color.grep・color.ui の always、grep.column）でも色も桁も付けず、同じ一致だけを同じ行で出す", (t) => {
  const { root, run } = refsFixture(t);
  const env = cleanEnv(gitConfigEnv({ "color.grep": "always", "color.ui": "always", "grep.column": "true" }));
  for (const id of ["イベント#1", "イベント#1.1"]) {
    const r = runNode(cradle, ["refs", id], { cwd: root, env });
    assert.deepEqual([r.status, r.stdout, r.stderr], [0, run(root, id).stdout, ""], id);
  }
});

test("refs は git の外や git が無いとき 0 箇所と言わず、git grep の失敗を stderr に 1 行出して 1 で終わる", (t) => {
  const outside = tempProject(t, "cradle-refs-nogit-");
  writeTree(outside, { "README.md": "イベント#1\n" });
  // 一時ディレクトリの祖先に git の作業ツリーがあっても、そこまで上がらせない。利用者の git 設定（grep.fallbackToNoIndex）で git の外を --no-index で探させない
  const env = cleanEnv({ GIT_CEILING_DIRECTORIES: dirname(outside), GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: "/dev/null" });
  const noRepo = runNode(cradle, ["refs", "イベント#1"], { cwd: outside, env });
  assert.equal(noRepo.status, 1);
  assert.equal(noRepo.stdout, "");
  assert.match(noRepo.stderr, /^cradle refs: git grep が失敗しました: \S.*\n$/);
  const noGit = runNode(cradle, ["refs", "イベント#1"], { cwd: outside, env: { ...env, PATH: tempDir(t, "cradle-no-tools-") } });
  assert.deepEqual([noGit.status, noGit.stdout, noGit.stderr], [1, "", "cradle refs: git grep が失敗しました: spawnSync git ENOENT\n"]);
});

